import { addDays, HOY } from '../lib/format.js'

// Los expedientes de muestra. `reqs` guarda el estado de cada requisito:
//   { estado: 'pendiente' | 'curso' | 'aportado', emitido, plantillaId, valores, nota }
// `emitido` es la fecha del documento, de la que se deriva la caducidad.

const d = (offset) => addDays(HOY, offset)

// Plantilla que la agencia usa por defecto para cada requisito. Un requisito ya
// trabajado llega con su plantilla puesta; los campos se precargan al abrirlo.
const PLANTILLA_POR_REQ = {
  'IN-01': 'plt-nota-simple',
  'IN-03': 'plt-cee',
  'IN-05': 'plt-deuda-cero',
  'IN-09': 'plt-suministros',
  'PT-03': 'plt-poder',
  'PT-05': 'plt-arras',
  'PT-06': 'plt-encargo',
  'FS-01': 'plt-medios-pago',
  'NT-02': 'plt-minuta'
}

function marcar(entradas) {
  const reqs = {}
  for (const [id, estado, offset, extra] of entradas) {
    reqs[id] = {
      estado,
      emitido: offset === null ? null : d(offset),
      plantillaId: estado === 'pendiente' ? null : PLANTILLA_POR_REQ[id] || null,
      valores: {},
      ...(extra || {})
    }
  }
  return reqs
}

